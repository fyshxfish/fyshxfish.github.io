#!/usr/bin/env python3
"""Generate the virtual text index; optionally package or preview the static site."""
import argparse
import hashlib
import json
import shutil
from functools import partial
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parent.parent
TEXT_ROOTS = (("content/books", "/books"), ("content/.diary", "/.diary"), ("content/pages", ""))


def generate_index(root=ROOT):
    files = {}
    for folder, prefix in TEXT_ROOTS:
        directory = root / folder
        if not directory.exists():
            continue
        for path in sorted(directory.rglob("*")):
            if path.is_symlink():
                raise ValueError(f"文章目录不支持符号链接：{path}")
            if not path.is_file() or path.suffix.lower() not in (".md", ".txt"):
                continue
            virtual = prefix + "/" + path.relative_to(directory).as_posix()
            if virtual in files:
                raise ValueError(f"虚拟路径重复：{virtual}")
            content = path.read_bytes()
            content.decode("utf-8")  # Fail at build time if a document isn't UTF-8.
            files[virtual] = {
                "type": "text",
                "src": path.relative_to(root).as_posix(),
                "format": "markdown" if path.suffix.lower() == ".md" else "text",
                "revision": hashlib.sha256(content).hexdigest()[:12],
            }
    metadata = json.dumps(dict(sorted(files.items())), ensure_ascii=False, indent=2)
    source = """// Generated by scripts/build.py. Edit the files in content/, not this index.
(function () {
  const files = %s;
  for (const path of Object.keys(files)) {
    if (Object.prototype.hasOwnProperty.call(window.FS.files, path)) {
      throw new Error(`文件路径重复：${path}`);
    }
  }
  Object.assign(window.FS.files, files);
})();
""" % metadata
    destination = root / "content-index.js"
    if not destination.exists() or destination.read_text(encoding="utf-8") != source:
        destination.write_text(source, encoding="utf-8")
    return files


def package_site(output):
    output = output.resolve()
    if output != ROOT / "_site":
        raise ValueError("部署目录固定为项目内的 _site，避免覆盖其他文件")
    if output.is_symlink():
        raise ValueError("部署目录不能是符号链接")
    if output.exists():
        shutil.rmtree(output)
    output.mkdir()
    for path in ROOT.iterdir():
        if path.is_file() and (path.suffix in (".html", ".css", ".js", ".ico", ".png", ".svg", ".webmanifest")
                               or path.name in ("CNAME", ".nojekyll")):
            shutil.copy2(path, output / path.name)
    # Hidden diary paths must remain in the deployment, just as in the index.
    for path in (ROOT / "content").rglob("*"):
        if path.is_symlink():
            raise ValueError(f"静态资源不支持符号链接：{path}")
    shutil.copytree(ROOT / "content", output / "content")
    (output / ".nojekyll").touch()


class PreviewHandler(SimpleHTTPRequestHandler):
    def do_GET(self):
        if urlsplit(self.path).path == "/content-index.js":
            generate_index()
        super().do_GET()

    def end_headers(self):
        self.send_header("Cache-Control", "no-cache")
        super().end_headers()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, help="将部署资源打包到 _site")
    parser.add_argument("--serve", action="store_true", help="本地预览，刷新时自动更新清单")
    parser.add_argument("--port", type=int, default=8000)
    args = parser.parse_args()
    if args.serve and args.output:
        parser.error("--serve 与 --output 请分别运行")
    files = generate_index()
    print(f"已生成文章清单：{len(files)} 个文件")
    if args.output:
        package_site(args.output)
        print("已打包到 _site/")
    if args.serve:
        server = ThreadingHTTPServer(("127.0.0.1", args.port), partial(PreviewHandler, directory=str(ROOT)))
        print(f"预览：http://127.0.0.1:{args.port}（新增文章后刷新页面即可）", flush=True)
        try:
            server.serve_forever()
        except KeyboardInterrupt:
            pass
        finally:
            server.server_close()


if __name__ == "__main__":
    main()
